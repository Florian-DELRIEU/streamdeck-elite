    /// <summary>
    /// "Alarme" action (com.mhwlng.elite.eventalarm, cahier des charges §5.3, docs/L8-alarme.md, docs/L10-v3.md): shows
    /// the alert image and plays the alert sound of an alarm when a journal event of its type (optionally filtered on one
    /// of its fields) is written live. Events replayed at startup never trigger it (IsLive guard). Up to 4 alarms per
    /// key (v3.6, AlarmSet): only the active one counts. The alert ends after its duration, or at a key press when the
    /// duration is 0. A press acknowledges the displayed alert, then sends its command, shortcut and click sound (at rest:
    /// those of alarm 1). A key that is not displayed (other page, closed folder) does not exist: it misses the events.
    /// </summary>
    [PluginActionId("com.mhwlng.elite.eventalarm")]
    public class EventAlarmAction : EliteKeypadBase
    {
        // property names = JSON names of EventAlarm.html; defaults apply to keys created before the setting existed
        protected class PluginSettings
        {
            [JsonProperty(PropertyName = "event")] public string Event { get; set; } = "";
            [JsonProperty(PropertyName = "filterField")] public string FilterField { get; set; } = "";
            [JsonProperty(PropertyName = "filterOp")] public string FilterOp { get; set; } = "";
            [JsonProperty(PropertyName = "filterValue")] public string FilterValue { get; set; } = "";
            [JsonProperty(PropertyName = "duration")] public string Duration { get; set; } = "5";
            [FilenameProperty]
            [JsonProperty(PropertyName = "idleImage")] public string IdleImage { get; set; } = "";
            [FilenameProperty]
            [JsonProperty(PropertyName = "activeImage")] public string ActiveImage { get; set; } = "";
            [FilenameProperty]
            [JsonProperty(PropertyName = "alarmSound")] public string AlarmSound { get; set; } = "";
            [JsonProperty(PropertyName = "pressCommand")] public string PressCommand { get; set; } = "";
            [JsonProperty(PropertyName = "pressHotkey")] public string PressHotkey { get; set; } = "";
            [JsonProperty(PropertyName = "pressHotkeyText")] public string PressHotkeyText { get; set; } = "";
            [FilenameProperty]
            [JsonProperty(PropertyName = "clickSound")] public string ClickSound { get; set; } = "";

            // ---- alarms 2 to 4 (same names + alarm number, idleImage is common): generated by tools/make-generic-html.py
            // <generated-alarms-2-4>
            [JsonProperty(PropertyName = "event2")] public string Event2 { get; set; } = "";
            [JsonProperty(PropertyName = "filterField2")] public string FilterField2 { get; set; } = "";
            [JsonProperty(PropertyName = "filterOp2")] public string FilterOp2 { get; set; } = "";
            [JsonProperty(PropertyName = "filterValue2")] public string FilterValue2 { get; set; } = "";
            [JsonProperty(PropertyName = "duration2")] public string Duration2 { get; set; } = "5";
            [FilenameProperty]
            [JsonProperty(PropertyName = "activeImage2")] public string ActiveImage2 { get; set; } = "";
            [FilenameProperty]
            [JsonProperty(PropertyName = "alarmSound2")] public string AlarmSound2 { get; set; } = "";
            [JsonProperty(PropertyName = "pressCommand2")] public string PressCommand2 { get; set; } = "";
            [JsonProperty(PropertyName = "pressHotkey2")] public string PressHotkey2 { get; set; } = "";
            [JsonProperty(PropertyName = "pressHotkeyText2")] public string PressHotkeyText2 { get; set; } = "";
            [FilenameProperty]
            [JsonProperty(PropertyName = "clickSound2")] public string ClickSound2 { get; set; } = "";
            [JsonProperty(PropertyName = "event3")] public string Event3 { get; set; } = "";
            [JsonProperty(PropertyName = "filterField3")] public string FilterField3 { get; set; } = "";
            [JsonProperty(PropertyName = "filterOp3")] public string FilterOp3 { get; set; } = "";
            [JsonProperty(PropertyName = "filterValue3")] public string FilterValue3 { get; set; } = "";
            [JsonProperty(PropertyName = "duration3")] public string Duration3 { get; set; } = "5";
            [FilenameProperty]
