            [JsonProperty(PropertyName = "pressHotkeyText4")] public string PressHotkeyText4 { get; set; } = "";
            [FilenameProperty]
            [JsonProperty(PropertyName = "clickSound4")] public string ClickSound4 { get; set; } = "";
            // </generated-alarms-2-4>
        }

        private readonly object sync = new object();
        private readonly KeyMedia media = new KeyMedia("EventAlarm");
        private PluginSettings settings = new PluginSettings();
        private AlarmSet alarms = AlarmSet.FromSettings(null);
        private string lastImage;
        private int? lastActive;
        private bool imageSent;
        private bool disposed;

        public EventAlarmAction(SDConnection connection, InitialPayload payload) : base(connection, payload)
        {
            try
            {
                var raw = payload.Settings ?? new JObject();
                settings = raw.Count == 0 ? new PluginSettings() : raw.ToObject<PluginSettings>();

                // saves the defaults of the settings added since the key was created
                Connection.SetSettingsAsync(JObject.FromObject(settings)).Wait();

                ApplySettings();
                EliteStore.JournalEventReceived += OnJournalEvent;
                Connection.OnSendToPlugin += OnSendToPlugin;
                Render(true);
            }
            catch (Exception ex)
            {
                Logger.Instance.LogMessage(TracingLevel.ERROR, $"EventAlarm: constructor failed: {ex}");
            }
        }

        public override void KeyPressed(KeyPayload payload)
        {
            try
            {
                AlarmConfig current;
                int? acknowledged;
                lock (sync)
                {
                    // only the displayed alarm counts; at rest, the command of alarm 1
                    acknowledged = alarms.Acknowledge(DateTime.UtcNow);
                    current = alarms.Config(acknowledged ?? 0);
                }

                // the alert is acknowledged before the command is sent (§5.3)
                if (acknowledged.HasValue)
                {
                    Logger.Instance.LogMessage(TracingLevel.INFO, $"EventAlarm[{current.Event}]: acknowledged");
                    Render(false);
                }

                KeyCommands.Send(Connection, current.Command, current.Hotkey, current.HotkeyText, $"EventAlarm[{current.Event}]");

                media.Play(current.ClickSound);
            }
            catch (Exception ex)
            {
                Logger.Instance.LogMessage(TracingLevel.ERROR, $"EventAlarm[{alarms?.Config(0).Event}]: key press failed: {ex}");
            }
        }

        public override void ReceivedSettings(ReceivedSettingsPayload payload)
        {
            try
            {
                BarRaider.SdTools.Tools.AutoPopulateSettings(settings, payload.Settings);
                ApplySettings();
                Connection.SetSettingsAsync(JObject.FromObject(settings)).Wait();
                Render(true);
            }
            catch (Exception ex)
            {
                Logger.Instance.LogMessage(TracingLevel.ERROR, $"EventAlarm: settings update failed: {ex}");
            }
        }

        /// <summary>
        /// About every second: the alert ends when its duration is over (redrawn only when the alert state changed).
        /// </summary>
        public override void OnTick()
        {
            base.OnTick();
            try
            {
                bool changed;
                lock (sync)
                    changed = imageSent && alarms.Active(DateTime.UtcNow) != lastActive;
                if (changed)
                    Render(false);
            }
            catch (Exception ex)
            {
                Logger.Instance.LogMessage(TracingLevel.ERROR, $"EventAlarm[{alarms?.Config(0).Event}]: tick failed: {ex}");
            }
        }

        public override void Dispose()
        {
            lock (sync)
                disposed = true;

            EliteStore.JournalEventReceived -= OnJournalEvent;
            Connection.OnSendToPlugin -= OnSendToPlugin;
            base.Dispose();
        }

        // background thread (journal watcher), for every journal line, replayed (IsLive false) or live
        private void OnJournalEvent(object sender, RawJournalEventArgs e)
        {
            try
            {
                var triggered = new List<AlarmConfig>();
                lock (sync)
                {
                    if (disposed)
                        return;
                    foreach (var index in alarms.Observe(e, DateTime.UtcNow))
                        triggered.Add(alarms.Config(index));
                }

                foreach (var current in triggered)
                {
                    Logger.Instance.LogMessage(TracingLevel.INFO, $"EventAlarm[{current.Event}]: triggered");
                    Alert(current);
                }
            }
            catch (Exception ex)
            {
                Logger.Instance.LogMessage(TracingLevel.ERROR, $"EventAlarm[{alarms?.Config(0).Event}]: event handling failed: {ex}");
            }
        }

        /// <summary>
        /// Property inspector: { alarmTest: true, alarmIndex: n } triggers alarm n (1 to 4) as a live event would
        /// ("Tester l'alarme" button);
        /// { genericValueRequest: key } asks for the current value of a key (the "i" panel: last event received).
        /// </summary>
        private void OnSendToPlugin(object sender, BarRaider.SdTools.Wrappers.SDEventReceivedEventArgs<BarRaider.SdTools.Events.SendToPlugin> e)
        {
            try
            {
                var payload = e?.Event?.Payload;
                if (payload == null)
                    return;

                if (payload["alarmTest"] != null)
                {
                    AlarmConfig current;
                    lock (sync)
                    {
                        if (disposed)
                            return;
                        int index = (payload["alarmIndex"] != null ? payload["alarmIndex"].Value<int>() : 1) - 1;
                        if (index < 0 || index >= alarms.Count)
                            index = 0;
                        current = alarms.Config(index);
                        alarms.Trigger(index, DateTime.UtcNow);
                    }

                    Logger.Instance.LogMessage(TracingLevel.INFO, $"EventAlarm[{current.Event}]: test from the property inspector");
                    Alert(current);
                    return;
                }

                var key = payload["genericValueRequest"];
                if (key != null)
                {
                    JToken value;
                    EliteStore.TryGet((string)key, out value);
                    var reply = ValueFormatter.DescribeCurrentValue((string)key, value, new ValueSettings(), DateTime.Now);
                    Watch(Connection.SendToPropertyInspectorAsync(reply), "SendToPropertyInspector");
                }
            }
            catch (Exception ex)
            {
                Logger.Instance.LogMessage(TracingLevel.ERROR, $"EventAlarm: property inspector request failed: {ex}");
            }
        }

        private void Alert(AlarmConfig current)
        {
            Render(false);

            // without an alert image the key would not change: the Stream Deck warning triangle shows the alert
            if (KeyMedia.ExistingFile(current.ActiveImage) == null)
                Watch(Connection.ShowAlert(), "ShowAlert");

            media.Play(current.AlarmSound);
        }

        private void ApplySettings()
        {
            var newAlarms = AlarmSet.FromSettings(JObject.FromObject(settings),
                (alarm, warning) => Logger.Instance.LogMessage(TracingLevel.WARN, $"EventAlarm[{settings.Event}] alarm {alarm}: {warning}"));

            lock (sync)
            {
                newAlarms.KeepStatesOf(alarms);
                alarms = newAlarms;
            }
        }

        /// <summary>
        /// Sends the image only when it changed (force: after creation or a settings change): alert image of the displayed
        /// alarm while an alert is active, idle image otherwise; the default image of the action when the file is missing.
        /// Nothing is awaited, so that the watcher threads are never blocked.
        /// </summary>
        private void Render(bool force)
        {
            lock (sync)
            {
                if (disposed)
                    return;

                var active = alarms.Active(DateTime.UtcNow);
                var image = KeyMedia.ExistingFile(active.HasValue ? alarms.Config(active.Value).ActiveImage : alarms.Config(0).IdleImage);
                lastActive = active;
                if (!force && imageSent && image == lastImage)
                    return;

                lastImage = image;
                imageSent = true;
                var base64 = image == null ? null : media.ImageBase64(image);
                if (base64 != null)
                    Watch(Connection.SetImageAsync(base64), "SetImage");
                else
                    Watch(Connection.SetDefaultImageAsync(), "SetDefaultImage");
            }
        }

        private void Watch(Task task, string what)
        {
            task.ContinueWith(t => Logger.Instance.LogMessage(TracingLevel.ERROR, $"EventAlarm[{alarms?.Config(0).Event}]: {what} failed: {t.Exception}"),
                TaskContinuationOptions.OnlyOnFaulted);
        }
    }
